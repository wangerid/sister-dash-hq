// The ten level maps (stored by world/theme id), level order and time limits.
//
// Levels are ASCII maps, 17 rows tall, tile = 32x32 px. Each level is written
// as a list of chunks (short ASCII pieces) that are joined left to right.
// Chunks are bottom-aligned: a chunk with fewer than 17 rows is padded with
// empty rows at the top, so most chunks only need their lower rows.
// Ground normally sits on rows 13-16 (the last 4 rows of a chunk).
//
// Legend
//   .  empty          #  ground         B  wooden box      ?  surprise box (coin)
//   C  surprise box (carrot)            X  cracked box     o  coin
//   D  surprise box (magic candy)       d  magic candy
//   c  magic carrot   h  hedgehog       f  frog            w  crow
//   s  spiky plant    k  checkpoint     F  goal flag       P  player start
//   m  mole hole      b  cave bat       R  rolling rock start
//   |  loose stalactite (falls)         n  mine cart platform (moves on rails)
//   ~  thin cloud (one-way)             g  rain cloud (vanishes)
//   ^  spring cloud   =  moving cloud   W  wind zone
//   l  cloudling      u  sky gull       y  spark
//   r  crab           j  jellyfish      p  pufferfish      e  eel hole
//   a  air bubble vent                  <  water current (pushes left)
//   >  water current (pushes right)     %  seaweed / coral (decoration)
//   z  scorpion       v  vulture        t  tumbleweed      q  quicksand
//   -  crumbling sandstone platform     K  boss arena start (boss spawns here)
// Extra characters used by these maps:
//   *  crystal coin (worth 5)           I  moving cloud (up and down)
//   _  rope bridge / thin ledge (one-way, like ~)
//   :  rainbow bridge (solid)           H  sunken-ship planks (solid)
//
// Notes: in level 2 "#" is drawn as cave rock, in level 4 as solid white
// cloud, in level 7 "s" is drawn as a cactus. Level 6 has underwater: true.
// The boss arena starts at the "K" column and is exactly 30 tiles (one
// screen) wide; the map ends with it.

var LEVEL_H = 17;

function buildMap(chunks) {
  var rows = [];
  var r, i;
  for (r = 0; r < LEVEL_H; r++) rows.push('');
  for (i = 0; i < chunks.length; i++) {
    var ch = chunks[i];
    var w = 0;
    for (r = 0; r < ch.length; r++) w = Math.max(w, ch[r].length);
    var pad = LEVEL_H - ch.length;
    for (r = 0; r < LEVEL_H; r++) {
      var line = r < pad ? '' : ch[r - pad];
      while (line.length < w) line += '.';
      rows[r] += line;
    }
  }
  return rows;
}

