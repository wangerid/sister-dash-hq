// Every level has 5 magic candies: one shortly after the start, one right
// after each of the first two checkpoints, one hidden, and one in the candy
// box by the checkpoint before the boss. Maps that were drawn with fewer get
// the missing ones placed on the main path here.
var SOLID_CH = '#~:_HBX?CDZ';
function placeOnPath(map, from, ch) {
  for (var x = from; x < from + 14; x++) {
    for (var y = map.length - 1; y >= 2; y--) {
      if (SOLID_CH.indexOf(map[y][x]) >= 0 && map[y - 1][x] === '.' && map[y - 2][x] === '.') {
        map[y - 1] = map[y - 1].substr(0, x) + ch + map[y - 1].substr(x + 1);
        return true;
      }
    }
  }
  return false;
}
function topUpCandies(map) {
  var n = 0, cps = [];
  for (var y = 0; y < map.length; y++) {
    for (var x = 0; x < map[y].length; x++) {
      var c = map[y][x];
      if (c === 'd' || c === 'D') n++;
      if (c === 'k') cps.push(x);
    }
  }
  if (n >= 5) return;
  cps.sort(function (a, b) { return a - b; });
  var want = [16, (cps[0] || 100) + 4, (cps[1] || 200) + 4];
  for (var i = 0; i < want.length && n < 5; i++) if (placeOnPath(map, want[i], 'd')) n++;
}

function buildLevels() {
  return LEVEL_DEFS.map(function (d, i) {
    var meta = LEVEL_META[d.theme] || {};
    for (var k in meta) d[k] = meta[k];
    d.index = i + 1;
    d.map = buildMap(LEVEL_CHUNKS[d.theme] || [[
      'P...........................................K.............................',
      '##########################################################################',
      '##########################################################################',
      '##########################################################################',
      '##########################################################################'
    ]]);
    topUpCandies(d.map);
    return d;
  });
}
var LEVELS = buildLevels();
